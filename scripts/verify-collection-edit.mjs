import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.TEST_URL||'http://localhost:4173';
for(const width of [375,768,1440,1920]){
 await page.setViewportSize({width,height:1000});
 await page.goto(base+'/collections.html');
 if(await page.locator('.cookie-banner').isVisible())await page.locator('[data-cookie="reject"]').first().click();
 await page.emulateMedia({reducedMotion:'reduce'});
 const cards=page.locator('.collection-grid .collection-item');
 await page.waitForFunction(()=>document.querySelector('.filter-count').textContent.includes('Showing'));
 assert.equal(await cards.count(),20);
 assert.equal(await cards.locator('visible=true').count(),6);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.locator('[data-show-more]').click();assert.equal(await cards.locator('visible=true').count(),12);
 await page.selectOption('[name=format]','table');await page.selectOption('[name=style]','plum');
 assert.equal(await cards.locator('visible=true').count(),3);
 await page.locator('[type=reset]').click();
 await page.selectOption('[name=format]','floral-relief');
 assert.equal(await cards.locator('visible=true').count(),1);
 assert.equal(await page.locator('.collection-item:visible .concept-label').isVisible(),true);
 await page.locator('.collection-item:visible .collection-photo').click();
 await page.waitForURL('**/enquiries.html?**');
 assert.match(await page.locator('[name=message]').inputValue(),/Sculptural Floral Relief \(concept\)/);
 await page.goto(base+'/atelier.html');
 assert.equal(await page.locator('.wall-options .collection-item').count(),4);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.locator('.wall-showcase').screenshot({path:`/tmp/wall-edit-${width}.png`});
 await page.goto(base+'/collections.html');
 await page.locator('.collection-item:visible img').evaluateAll(images=>Promise.all(images.map(img=>{img.loading='eager';return img.decode();})));
 await page.locator('.collections-shell').screenshot({path:`/tmp/color-edit-${width}.png`});
}
await page.goto(base+'/collections.html?format=framed-moss');
await page.waitForFunction(()=>document.querySelector('.filter-count').textContent.includes('Showing'));
assert.equal(await page.locator('.collection-item:visible').count(),1);
await page.selectOption('[name=style]','blue');assert.equal(await page.locator('.empty-state').isVisible(),true);
await page.locator('[data-reset-filters]').click();assert.equal(await page.locator('.collection-item:visible').count(),6);
const context=await browser.newContext({javaScriptEnabled:false});const nojs=await context.newPage();
await nojs.goto(base+'/collections.html');assert.equal(await nojs.locator('.collection-item:visible').count(),20);
assert.deepEqual(errors,[]);await browser.close();
console.log('Collection edit: 20 choices, pagination, palettes, formats, concept enquiry, responsive layouts and no-JS passed.');
